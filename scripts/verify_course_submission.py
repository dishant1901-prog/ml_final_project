#!/usr/bin/env python3
"""Fail-fast verification for the course repository and report deliverables."""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import subprocess

from pypdf import PdfReader
import yaml


ROOT = Path(__file__).resolve().parents[1]
RECEIPT = ROOT / "data" / "course-submission" / "course-submission-verification.json"
REQUIRED = [
    "README.md", "COURSE_SUBMISSION.md", "REPRODUCIBILITY.md", "DATASETS.md",
    "CHECKPOINTS.md", "MODEL_CARD.md", "environment.yml", "requirements.txt",
    "requirements-model.txt", "uv.lock", "pyproject.toml", "course-report/main.tex",
    "course-report/main.bib", "course-report/authors.tex",
    "course-report/HimaRoad_Flood_Copilot_CVPR.pdf", "tests", "src/himaroad",
    "backend/app", "scripts/ci_local.sh",
]
ASSISTANCE_MARKERS = re.compile(
    r"\b(AI[- ]assisted|generated by AI|AI assistance)\b", re.I)


def command(*args: str) -> str:
    return subprocess.check_output(args, cwd=ROOT, text=True).strip()


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--strict-authors", action="store_true")
    parser.add_argument("--no-write", action="store_true",
                        help="verify without replacing the tracked JSON receipt")
    args = parser.parse_args()
    errors: list[str] = []
    notices: list[str] = []

    for item in REQUIRED:
        if not (ROOT / item).exists():
            errors.append(f"missing required path: {item}")

    tracked = set(command("git", "ls-files").splitlines())
    for forbidden in (".env", "data/private/internal-credentials.txt"):
        if forbidden in tracked:
            errors.append(f"secret/private path is tracked: {forbidden}")
    if any(path == "data" or path.startswith("data/") for path in tracked):
        errors.append("large/generated data directory contains tracked files")
    if "conversation-handoff-2026-10-24.md" in tracked:
        errors.append("private conversation handoff must not be published")

    authors = (ROOT / "course-report" / "authors.tex").read_text(encoding="utf-8")
    placeholders = sorted(set(re.findall(r"\\Pending\{([^}]+)\}", authors)))
    if placeholders:
        message = "author/course/repository placeholders remain: " + ", ".join(placeholders)
        (errors if args.strict_authors else notices).append(message)

    public_submission_files = [
        ROOT / "COURSE_SUBMISSION.md", ROOT / "REPRODUCIBILITY.md",
        ROOT / "DATASETS.md", ROOT / "CHECKPOINTS.md",
        ROOT / "course-report" / "main.tex", ROOT / "course-report" / "authors.tex",
    ]
    for path in public_submission_files:
        match = ASSISTANCE_MARKERS.search(path.read_text(encoding="utf-8"))
        if match:
            errors.append(f"submission assistance marker in {path.relative_to(ROOT)}: {match.group(0)}")

    report = ROOT / "course-report" / "HimaRoad_Flood_Copilot_CVPR.pdf"
    pages = len(PdfReader(str(report)).pages) if report.is_file() else None
    if pages != 8:
        errors.append(f"CVPR report page count is {pages}, expected 8")

    env = yaml.safe_load((ROOT / "environment.yml").read_text(encoding="utf-8"))
    if not env.get("dependencies"):
        errors.append("environment.yml has no dependencies")
    cfg = yaml.safe_load((ROOT / "configs" / "model_unet.yaml").read_text(encoding="utf-8"))
    expected_model_hash = "3ed60130587f4c9562653d4cd9b389e41e4df21030d90eb85ea2d33f7a7098e5"
    if cfg.get("checkpoint_sha256") != expected_model_hash:
        errors.append("registered model checkpoint hash changed")
    if (ROOT / cfg["checkpoint"]).exists():
        actual = digest(ROOT / cfg["checkpoint"])
        if actual != expected_model_hash:
            errors.append("local checkpoint exists but does not match the registered hash")
    else:
        notices.append("registered UNet checkpoint absent, as declared in CHECKPOINTS.md")

    history = command("git", "log", "--date=iso-strict", "--pretty=format:%H\t%aI\t%an\t%s")
    dirty = command("git", "status", "--porcelain")
    receipt = {
        "schema": 1,
        "verified_utc": datetime.now(timezone.utc).isoformat(),
        "status": "failed" if errors else "passed",
        "branch": command("git", "branch", "--show-current"),
        "head": command("git", "rev-parse", "HEAD"),
        "head_timestamp": command("git", "show", "-s", "--format=%cI", "HEAD"),
        "report_pages": pages,
        "report_sha256": digest(report) if report.is_file() else None,
        "commit_history_tsv": history,
        "working_tree_dirty": bool(dirty),
        "notices": notices,
        "errors": errors,
    }
    if not args.no_write:
        RECEIPT.parent.mkdir(parents=True, exist_ok=True)
        RECEIPT.write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    for item in notices:
        print("NOTICE:", item)
    if errors:
        for item in errors:
            print("ERROR:", item)
        return 1
    print(f"PASS: course submission structure; report={pages} pages; HEAD={receipt['head'][:12]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
